-- Run this in Snowflake Worksheets once before triggering DAG
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH 
  WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS FLIGHT_DB;
USE DATABASE FLIGHT_DB;

CREATE SCHEMA IF NOT EXISTS BRONZE;
CREATE SCHEMA IF NOT EXISTS SILVER;
CREATE SCHEMA IF NOT EXISTS GOLD;

-- Bronze setup
CREATE STAGE IF NOT EXISTS BRONZE.FLIGHT_STAGE;
CREATE TABLE IF NOT EXISTS BRONZE.RAW_FLIGHTS (
    raw_data VARIANT,
    file_name STRING,
    ingested_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Silver setup
CREATE TABLE IF NOT EXISTS SILVER.CLEAN_FLIGHTS (
    icao24 STRING,
    callsign STRING,
    origin_country STRING,
    time_position TIMESTAMP_NTZ,
    longitude FLOAT,
    latitude FLOAT,
    altitude_feet FLOAT,
    velocity_knots FLOAT,
    on_ground BOOLEAN,
    updated_at TIMESTAMP_NTZ
);
